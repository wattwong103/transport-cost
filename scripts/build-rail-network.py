#!/usr/bin/env python3
"""
Build the Bangkok rail network from OpenStreetMap station nodes keyed by
their official station codes (BL01, N8, E4, PP16, ...).

Input : data/osm-stations.json   (scripts/fetch-osm-stations.py)
Output: data/rail-network.json

Each line is an ordered list of official codes, so the topology (including
the MRT Blue Line loop) is explicit instead of being inferred from
coordinates. Stations shared by two lines of the same operator (BTS Siam,
SRT Krung Thep Aphiwat) are a single station; interchanges between
different stations are generated by proximity and listed for review.
"""

import json
import math
import os
import re
from collections import defaultdict
from datetime import date

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OSM_PATH = os.path.join(REPO, 'data', 'osm-stations.json')
OUT_PATH = os.path.join(REPO, 'data', 'rail-network.json')

TRANSFER_RADIUS_M = 450      # stations of different lines closer than this get a walking transfer
TRANSFER_DETOUR = 1.3        # street-network detour factor
TRANSFER_VERTICAL_M = 80     # stairs / concourse equivalent distance
# official interchanges whose platforms are further apart than TRANSFER_RADIUS_M
KNOWN_TRANSFERS = [('PK01', 'PP11'), ('A4', 'YL11')]


def seq(prefix, a, b, width=2, skip=()):
    step = 1 if b >= a else -1
    return [f'{prefix}{i:0{width}d}' for i in range(a, b + step, step) if i not in skip]


# fare ids match data/transport-modes.json
LINES = [
    {'id': 'bts_sukhumvit', 'name': 'BTS Sukhumvit Line', 'nameTh': 'บีทีเอส สายสุขุมวิท',
     'color': '#7CB342', 'fare': 'bts',
     'stations': seq('N', 24, 1, 1, skip={6}) + ['CEN'] + seq('E', 1, 23, 1)},
    {'id': 'bts_silom', 'name': 'BTS Silom Line', 'nameTh': 'บีทีเอส สายสีลม',
     'color': '#1B7F3B', 'fare': 'bts',
     'stations': ['W1', 'CEN'] + seq('S', 1, 12, 1)},
    {'id': 'gold', 'name': 'Gold Line', 'nameTh': 'สายสีทอง',
     'color': '#C9A227', 'fare': 'gold',
     'stations': ['G1', 'G2', 'G3']},
    {'id': 'mrt_blue', 'name': 'MRT Blue Line', 'nameTh': 'เอ็มอาร์ที สายสีน้ำเงิน',
     'color': '#1E4FA0', 'fare': 'mrt_blue',
     # Loop: Tha Phra (BL01) ... Itsaraphap (BL32) -> back to Tha Phra -> Bang Phai (BL33) ... Lak Song
     'stations': seq('BL', 1, 32) + ['BL01'] + seq('BL', 33, 38)},
    {'id': 'mrt_purple', 'name': 'MRT Purple Line', 'nameTh': 'เอ็มอาร์ที สายสีม่วง',
     'color': '#7B3F98', 'fare': 'mrt_purple',
     'stations': seq('PP', 1, 16)},
    {'id': 'mrt_pink', 'name': 'MRT Pink Line', 'nameTh': 'สายสีชมพู',
     'color': '#E5559E', 'fare': 'mrt_pink',
     'stations': seq('PK', 1, 30)},
    {'id': 'mrt_pink_mt', 'name': 'MRT Pink Line (Muang Thong Thani branch)', 'nameTh': 'สายสีชมพู ส่วนต่อขยายเมืองทองธานี',
     'color': '#E5559E', 'fare': 'mrt_pink',
     'stations': ['PK10', 'MT01', 'MT02']},
    {'id': 'mrt_yellow', 'name': 'MRT Yellow Line', 'nameTh': 'สายสีเหลือง',
     'color': '#F2C400', 'fare': 'mrt_yellow',
     'stations': seq('YL', 1, 23)},
    {'id': 'arl', 'name': 'Airport Rail Link', 'nameTh': 'แอร์พอร์ต เรล ลิงก์',
     'color': '#C8102E', 'fare': 'arl',
     'stations': seq('A', 1, 8, 1)},
    {'id': 'srt_dark_red', 'name': 'SRT Dark Red Line', 'nameTh': 'สายสีแดงเข้ม',
     'color': '#B71C1C', 'fare': 'srt_red',
     'stations': seq('RN', 1, 10)},
    {'id': 'srt_light_red', 'name': 'SRT Light Red Line', 'nameTh': 'สายสีแดงอ่อน',
     'color': '#E57373', 'fare': 'srt_red',
     'stations': ['RN01', 'RW02', 'RW05', 'RW06']},
]

# OSM refs that are not the official code
REF_ALIASES = {
    'กภ.': 'RN01', 'RW01': 'RN01', 'ซอ': 'RW02', 'บำ.': 'RW05', 'ตช.': 'RW06',
    '1': 'G1',
}
# stations OSM has without a ref: code -> English name to look up
NAME_FALLBACK = {
    'YL01': 'Lat Phrao', 'YL16': 'Si Udom', 'YL21': 'Si Thepha', 'YL22': 'Thipphawan',
}
# stations missing from the OSM extract entirely
MANUAL = {
    'N2': {'name': 'Phaya Thai', 'nameTh': 'พญาไท', 'lat': 13.75693, 'lng': 100.53380},
}
# preferred English names where OSM spelling is unusual
NAME_OVERRIDES = {
    'RN08': 'Don Mueang', 'RN09': 'Lak Hok', 'RW06': 'Taling Chan',
}


TWO_DIGIT = {'BL', 'PP', 'PK', 'YL', 'RN', 'RW', 'MT'}


def normalize_ref(ref):
    """'PP1' -> 'PP01', 'N08' -> 'N8' (official code widths differ per line)."""
    m = re.match(r'^([A-Z]+)0*(\d+)$', ref)
    if not m:
        return ref
    prefix, num = m.group(1), int(m.group(2))
    return f'{prefix}{num:02d}' if prefix in TWO_DIGIT else f'{prefix}{num}'


def hav_m(a, b):
    R = 6371000
    dlat = math.radians(b[0] - a[0])
    dlng = math.radians(b[1] - a[1])
    h = (math.sin(dlat / 2) ** 2 + math.cos(math.radians(a[0])) *
         math.cos(math.radians(b[0])) * math.sin(dlng / 2) ** 2)
    return 2 * R * math.asin(math.sqrt(h))


def main():
    osm = json.load(open(OSM_PATH, encoding='utf-8'))['stations']

    by_code = defaultdict(list)
    by_name = defaultdict(list)
    for s in osm:
        if s.get('railway') == 'construction':
            continue
        refs = [r.strip() for r in (s.get('ref') or '').split(';') if r.strip()]
        for r in refs:
            by_code[normalize_ref(REF_ALIASES.get(r, r))].append(s)
        if not refs:
            by_name[(s.get('name_en') or '').strip()].append(s)

    needed = []
    for line in LINES:
        for c in line['stations']:
            if c not in needed:
                needed.append(c)

    stations = {}
    problems = []
    for code in needed:
        cands = by_code.get(code) or by_name.get(NAME_FALLBACK.get(code, '\0'), [])
        if code in MANUAL:
            m = MANUAL[code]
            stations[code] = {'name': m['name'], 'nameTh': m['nameTh'],
                              'lat': m['lat'], 'lng': m['lng'], 'source': 'manual'}
            continue
        if not cands:
            problems.append(code)
            continue
        lat = sum(c['lat'] for c in cands) / len(cands)
        lng = sum(c['lon'] for c in cands) / len(cands)
        spread = max(hav_m((lat, lng), (c['lat'], c['lon'])) for c in cands)
        if spread > 250:
            problems.append(f'{code} duplicates spread {spread:.0f} m')
        best = cands[0]
        stations[code] = {
            'name': NAME_OVERRIDES.get(code) or best.get('name_en') or best.get('name'),
            'nameTh': best.get('name_th') or best.get('name') or '',
            'lat': round(lat, 6), 'lng': round(lng, 6),
            'source': f"osm:{best['osm_id']}",
        }

    if problems:
        raise SystemExit(f'Unresolved stations: {problems}')

    for line in LINES:
        for c in line['stations']:
            stations[c].setdefault('lines', [])
            if line['id'] not in stations[c]['lines']:
                stations[c]['lines'].append(line['id'])

    # Sanity: consecutive stations on a line should be 0.3-5 km apart
    for line in LINES:
        st = line['stations']
        for a, b in zip(st, st[1:]):
            d = hav_m((stations[a]['lat'], stations[a]['lng']), (stations[b]['lat'], stations[b]['lng']))
            if not 250 <= d <= 5500:
                print(f"  WARN {line['id']}: {a}->{b} {d:.0f} m")

    # Walking transfers between different stations of different lines
    codes = list(stations)
    transfers = []
    for i, a in enumerate(codes):
        for b in codes[i + 1:]:
            if set(stations[a]['lines']) & set(stations[b]['lines']):
                continue
            d = hav_m((stations[a]['lat'], stations[a]['lng']), (stations[b]['lat'], stations[b]['lng']))
            if d <= TRANSFER_RADIUS_M or (a, b) in KNOWN_TRANSFERS or (b, a) in KNOWN_TRANSFERS:
                walk = round(d * TRANSFER_DETOUR + TRANSFER_VERTICAL_M)
                transfers.append({'a': a, 'b': b, 'walk_m': walk})

    print(f'Stations: {len(stations)}  Lines: {len(LINES)}  Transfers: {len(transfers)}')
    for t in sorted(transfers, key=lambda t: t['walk_m']):
        print(f"  {t['walk_m']:4d} m  {t['a']:5s} {stations[t['a']]['name']:28s} <-> {t['b']:5s} {stations[t['b']]['name']}")

    out = {
        'meta': {
            'source': 'OpenStreetMap contributors (ODbL), station nodes with official ref codes',
            'built': date.today().isoformat(),
        },
        'lines': LINES,
        'stations': stations,
        'transfers': transfers,
    }
    with open(OUT_PATH, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print(f'Wrote {OUT_PATH}')


if __name__ == '__main__':
    main()
